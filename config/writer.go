package config

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"strings"

	pelletiertoml "github.com/pelletier/go-toml/v2"
)

// ============================================================
// 配置文件序列化与原子写 (Phase: config CRUD)
//
// 用途: mysshw config add/remove/update/export 都需要把内存中的
//       *Configs 写回磁盘。本文件封装:
//         1. serializeConfigs   *Configs → TOML 字节 (用 pelletier/go-toml/v2)
//         2. validateAndSerialize *Configs → TOML + ValidateConfig 预校验
//         3. writeConfigAtomic  tmp 文件 + rename 原子写
//         4. readConfigOrEmpty  读文件或返回空 *Configs (适合新建场景)
//
// 安全: writeConfigAtomic 自动 0600 权限 + 写前备份 (复用 backup_config.go)
//
// 不依赖 viper (因为它丢注释), 用 pelletier 直接序列化结构体, 输出格式稳定
// ============================================================

// SerializeConfigs 把 *Configs 序列化为 TOML 字节
//
// 输出格式:
//   - 顶层字段按 struct 顺序输出
//   - 字符串默认单引号 (TOML spec 兼容)
//   - 数组按原顺序输出
//   - 不输出空 map / 空数组 (避免冗余)
//
// 注: pelletier/go-toml/v2 的 Marshal 不带注释. 这是预期行为
//
//	(用户用 crud 修改的字段都靠 schema, 不需要保留原注释)
func SerializeConfigs(c *Configs) ([]byte, error) {
	if c == nil {
		return nil, errors.New("mysshw:: nil config")
	}
	data, err := pelletiertoml.Marshal(c)
	if err != nil {
		return nil, fmt.Errorf("mysshw:: marshal config: %w", err)
	}
	return data, nil
}

// validateAndSerialize 验证 + 序列化为 TOML 字节
//
// 返回: 序列化后的字节
// 错误: 验证失败时返回具体错误, 不写文件
func validateAndSerialize(c *Configs) ([]byte, error) {
	if c == nil {
		return nil, errors.New("mysshw:: nil config")
	}
	// 1. 先序列化 (验证 schema 合法性, 例如 enum 错误会在 Marshal 阶段抛出)
	data, err := SerializeConfigs(c)
	if err != nil {
		return nil, err
	}
	// 2. 验证 业务规则 (依赖 ValidateConfig)
	if err := ValidateConfig(c); err != nil {
		return nil, fmt.Errorf("mysshw:: validate config: %w", err)
	}
	// 3. 反向验证: 序列化结果能再次解析回来 (防双向不一致)
	var parsed Configs
	if err := pelletiertoml.Unmarshal(data, &parsed); err != nil {
		return nil, fmt.Errorf("mysshw:: round-trip parse failed: %w", err)
	}
	_ = parsed // 仅验证可解析, 不深度对比 (要容忍注释 / 空白差异)
	return data, nil
}

// readConfigOrEmpty 读 TOML 文件, 失败或不存在时返回空 *Configs
//
// 注意: 文件名校验 (mysshw.toml/mysshw 前缀) 由调用方 (Loader) 处理
//
//	此函数只负责读 + 解析
func ReadConfigOrEmpty(path string) (*Configs, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return &Configs{}, nil
		}
		return nil, fmt.Errorf("mysshw:: read %q: %w", path, err)
	}

	c := &Configs{}
	if err := pelletiertoml.Unmarshal(data, c); err != nil {
		return nil, fmt.Errorf("mysshw:: parse %q: %w", path, err)
	}
	return c, nil
}

// WriteConfigAtomic 原子地写入配置: 校验 → 序列化 → 备份 → 临时文件 → rename → 0600
//
// 与 backup_config.go::WriteTomlWithBackup 的区别:
//   - WriteTomlWithBackup 接受 []byte (低层)
//   - WriteConfigAtomic 接受 *Configs (高层, 自动校验 + 序列化)
//
// 调用方负责:
//   - 已调用 LoadViperConfig 加载到全局 CFG (或提供临时结构体)
//   - 已确认 path 是合法 mysshw.toml 路径
//
// 失败时不写盘; 调用方应处理 error 并考虑回滚
func WriteConfigAtomic(path string, c *Configs) error {
	if c == nil {
		return errors.New("mysshw:: nil config")
	}
	data, err := validateAndSerialize(c)
	if err != nil {
		return err
	}
	return WriteTomlWithBackup(path, data)
}

// canonicalCommentHeader 返回 TOML 文件的标准注释头 (用户编辑时能看懂)
// 用于 writer 在文件最前面追加一段解释
//
// 注: 实际写文件时不调用此函数 (保留注释会破坏写回幂等性); 只在
// export --with-template 时使用
func canonicalCommentHeader() string {
	var b bytes.Buffer
	b.WriteString("# mysshw 配置文件 (auto-generated by `mysshw config`)\n")
	b.WriteString("# 格式参考: https://github.com/cnphpbb/mysshw/blob/master/readme.md#config\n")
	b.WriteString("# 警告: 此文件由程序维护, 手工编辑请用 `mysshw config <subcmd>` 命令\n")
	b.WriteString("#\n")
	b.WriteString("# 字段类型 + 必填性:\n")
	b.WriteString("#   cfg_dir          string  配置目录 (死代码, 实际未读)\n")
	b.WriteString("#   known_hosts_path string  自定义主机指纹存储路径\n")
	b.WriteString("#   backup_keep      int     写 TOML 时保留的备份数\n")
	b.WriteString("#   encryption_algorithm  string  KDF 算法\n")
	b.WriteString("#   secret_key       string  KDF pepper (推荐 env 引用)\n")
	b.WriteString("#   cipher           string  文件级加密算法 (Phase C)\n")
	b.WriteString("#   kdf_params       string  KDF 调优参数 (JSON)\n")
	b.WriteString("#\n")
	b.WriteString("# [sync] 块: SCP/WebDAV/S3 配置同步参数\n")
	b.WriteString("# [[nodes]]  块: 一个 group (一个或多个 SSH 节点)\n")
	b.WriteString("#\n")
	b.WriteString("# 密码字段推荐方式 (4 种, 优先级递减):\n")
	b.WriteString("#   1. password = \"${MYSSHW_PWD_xxx}\"  env 引用 (推荐)\n")
	b.WriteString("#   2. password = \"$2a$10$xxxx...\"       bcrypt 哈希 (推荐)\n")
	b.WriteString("#   3. password = \"$2a$10$xxxx...\" --algo=bcrypt-pepper (需 secret_key)\n")
	b.WriteString("#   4. password = \"plain\"               明文 (⚠️ 仅测试)\n")
	b.WriteString("#\n")
	b.WriteString("# 整个文件也可用 passphrase 加密: `mysshw encrypt -c myssshw.toml`\n")
	b.WriteString("# 加密后以 'MSEC' magic 头开始, 仍是合法 mysshw.toml 路径\n")
	return b.String()
}

// hasBcryptOrEnv 简易密码检测 (给 CLI 警告用)
// true: 看起来是 bcrypt 哈希 或 env 引用
func hasBcryptOrEnv(p string) bool {
	if p == "" {
		return false
	}
	if IsBcryptHash(p) {
		return true
	}
	if strings.HasPrefix(strings.TrimSpace(p), "${") && strings.HasSuffix(strings.TrimSpace(p), "}") {
		return true
	}
	return false
}
